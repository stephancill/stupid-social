#!/usr/bin/env python3
"""Builds Resources/en.lproj/Localizable.strings from Telegram's push templates (core.telegram.org/api/config.json).

Telegram's APNs pushes (token_type 1) are alerts with `loc-key` and `loc-args`, which iOS formats with the app's
Localizable.strings; a key missing there shows as the bare key ("MESSAGE_TEXT"). Templates use `{1}`, `{2}`…,
which become positional `%1$@`, `%2$@`…

Usage:
  python3 scripts/telegram-push-strings.py              # downloads config.json
  python3 scripts/telegram-push-strings.py config.json
"""

import json
import pathlib
import re
import sys
import urllib.request

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "Resources/en.lproj/Localizable.strings"


def main() -> None:
    if len(sys.argv) == 2:
        config = json.loads(pathlib.Path(sys.argv[1]).read_text())
    else:
        with urllib.request.urlopen("https://core.telegram.org/api/config.json") as response:
            config = json.load(response)
    lines = [f"/* Telegram push templates, layer {config.get('layer')}, generated by scripts/telegram-push-strings.py. */", ""]
    for key, template in sorted(config["push"].items()):
        # A literal % would be read as a format directive.
        text = template.replace("%", "%%")
        text = re.sub(r"\{(\d+)\}", lambda m: f"%{m.group(1)}$@", text)
        text = text.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")
        lines.append(f'"{key}" = "{text}";')
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text("\n".join(lines) + "\n")
    print(f"Wrote {OUTPUT.relative_to(ROOT)}: {len(config['push'])} templates")


if __name__ == "__main__":
    main()
